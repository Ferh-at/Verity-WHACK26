from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from app.artifacts import MOCKS, benchmark, read, run_file
from app.metrics import benchmark_metrics
from app.present import AMBER, BLUE, MINT, heading, pct, plot, shell, source_note

shell("Proof")
heading("02", "Proof", "We planted real signals and traps where we know the right answer, then counted the mistakes.")
st.markdown(
    "Each seed builds 200 synthetic hypotheses: 10 real signals of known strength and 190 fakes. The fakes are "
    "pure noise plus traps that fool naive backtests: look-ahead leaks, one-month outliers, signals that only "
    "worked early on, disguised market beta and near-duplicate copies. "
    "The naive baseline trusts anything with a one-sided t-test p below 0.05."
)
records, demo = benchmark()
if demo:
    source_note(True, "Planted-trap benchmark")
else:
    st.caption("Synthetic data generated by our benchmark (engine/benchmark.py). No market data is used here.")
m = benchmark_metrics(records, None if demo else run_file("benchmark_metrics.json"))
noise = run_file("noise_search.json") or read(MOCKS / "recorded_benchmark/noise_search.json", {})
a, b, c = st.columns(3)
a.metric("Seeds", m["seeds"])
b.metric("Hypotheses tested", f"{m['trials']:,}")
c.metric("Pure-noise searches with a trusted result",
         f"{round(noise['share_with_trusted'] * noise['n_searches'])} of {noise['n_searches']}"
         if noise.get("n_searches") else "—")

left, right = st.columns(2)
with left:
    st.markdown("**How often a trusted idea is actually fake**")
    fig = go.Figure()
    for name, info, color in (("Naive t-test", m["naive"], AMBER), ("Verity", m["ours"], MINT)):
        if not info:
            continue
        err = None
        if info.get("ci"):
            low, high = info["ci"]
            err = dict(type="data", symmetric=False, array=[high - info["mean"]], arrayminus=[info["mean"] - low])
        fig.add_bar(x=[name], y=[info["mean"]], error_y=err, marker_color=color, name=name,
                    text=[pct(info["mean"], 1)], textposition="outside",
                    hovertemplate="%{x}<br>FDR %{y:.1%}<extra></extra>")
    fig.update_yaxes(tickformat=".0%", range=[0, 1])
    st.plotly_chart(plot(fig, y="False discovery rate", legend=False), use_container_width=True)
    st.caption("False discovery rate: the share of trusted ideas that were planted fakes. Mean across seeds, "
               "with a 95% bootstrap interval over seeds.")
with right:
    st.markdown("**How often a real signal is found, by strength**")
    recall = sorted((float(sr), rate) for sr, rate in m["recall"].items())
    if recall:
        fig = go.Figure(go.Bar(x=[str(sr) for sr, _ in recall], y=[val for _, val in recall], marker_color=BLUE,
                               text=[pct(val) for _, val in recall], textposition="outside"))
        fig.update_xaxes(type="category")
        fig.update_yaxes(tickformat=".0%", range=[0, 1.1])
        st.plotly_chart(plot(fig, "Planted annual Sharpe ratio", "Found (recall)", legend=False),
                        use_container_width=True)
    st.caption("The trade-off we chose: strong signals are found reliably, weak ones (Sharpe 0.5) are not. "
               "With 15 years of monthly discovery data, a weak signal cannot be told apart from luck. "
               "We would rather miss a real idea than trust a lucky one.")

table = pd.DataFrame.from_dict(m["grid"], orient="index").fillna(0).astype(int).sort_index()
table.index.name = "Planted type"
with st.expander("Which check stopped each planted type (all seeds)"):
    st.dataframe(table, use_container_width=True)
    st.caption("Columns name the first check each hypothesis failed. \"Trusted\" means it passed everything.")
